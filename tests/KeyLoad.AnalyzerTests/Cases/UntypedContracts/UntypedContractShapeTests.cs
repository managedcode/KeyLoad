namespace KeyLoad.AnalyzerTests.CodeQuality;

internal sealed class UntypedContractShapeTests
{
    [Test]
    [Arguments("object")]
    [Arguments("object?")]
    [Arguments("System.Object")]
    [Arguments("global::System.Object")]
    [Arguments("dynamic")]
    [Arguments("System.Threading.Tasks.Task<ManagedCode.Communication.Result<object>>")]
    [Arguments("System.Threading.Tasks.ValueTask<System.Collections.Generic.List<object?>>")]
    [Arguments("System.Collections.Generic.Dictionary<string, System.Threading.Tasks.Task<object[]>>")]
    [Arguments("(string Name, object Value)")]
    [Arguments("System.Func<System.Threading.Tasks.Task<object?>>")]
    [Arguments("System.Collections.IEnumerable")]
    [Arguments("System.Collections.Hashtable")]
    [Arguments("System.Threading.Tasks.Task<System.Collections.IList>")]
    public async Task ErasedReturnShapesReportOneLocatedWarning(string shape)
    {
        var source = "#nullable enable\ninternal abstract class Subject { internal abstract " + shape + " Read(); }";
        var findings = await UntypedContractAnalyzerFixture.ContractsAsync(source);
        await UntypedContractAnalyzerFixture.LocatedAsync(findings, UntypedContractAnalyzerFixture.ContractId,
            source, shape);
    }

    [Test]
    public async Task AliasResolvesToActualSystemObject()
    {
        const string source = "using Payload = System.Object; internal abstract class Subject { internal abstract Payload Read(); }";
        var findings = await UntypedContractAnalyzerFixture.ContractsAsync(source);
        await UntypedContractAnalyzerFixture.LocatedAsync(findings, UntypedContractAnalyzerFixture.ContractId,
            source, "Payload");
    }

    [Test]
    public async Task TypedGenericsAndAnUnrelatedObjectNamedClassRemainTyped()
    {
        const string source = """
            namespace Domain
            {
                internal sealed class @object { }
                internal abstract class Subject
                {
                    internal abstract System.Threading.Tasks.Task<@object[]> Read();
                    internal T Keep<T>(T value) => value;
                }
            }
            """;
        var findings = await UntypedContractAnalyzerFixture.ContractsAsync(source);
        await Assert.That(findings).IsEmpty();
    }

    [Test]
    public async Task FieldsPropertiesParametersAndLocalFunctionsHaveTheirOwnDeclarations()
    {
        const string source = """
            internal sealed class Subject
            {
                private object[] items = [];
                internal System.Func<object> Read { get; init; } = null!;
                internal void Accept(object value)
                {
                    object Local() => throw new System.InvalidOperationException();
                }
            }
            """;
        var findings = await UntypedContractAnalyzerFixture.ContractsAsync(source);
        await UntypedContractAnalyzerFixture.LocatedAsync(findings, UntypedContractAnalyzerFixture.ContractId,
            source, "object[]", "[]", "System.Func<object>", "object", "object");
    }

    [Test]
    public async Task ActualOrleansMetadataDoesNotAuthorizeAnErasedApplicationProperty()
    {
        const string source = """
            [Orleans.GenerateSerializer]
            internal sealed class Subject
            {
                [Orleans.Id(0)] public object Value { get; init; } = new();
            }
            """;
        var findings = await UntypedContractAnalyzerFixture.ContractsAsync(source);
        await UntypedContractAnalyzerFixture.LocatedAsync(findings, UntypedContractAnalyzerFixture.ContractId,
            source, "object", "new()");
    }

    [Test]
    public async Task GeneratedCodecSourceDoesNotDuplicateAuthoredContractWarnings()
    {
        const string source = "// <auto-generated/>\ninternal abstract class Codec { internal abstract object Read(); }";
        var findings = await UntypedContractAnalyzerFixture.AnalyzeAsync(new UntypedDataContractAnalyzer(),
            source, AnalyzerFixture.GeneratedPath);
        await Assert.That(findings).IsEmpty();
    }
}
