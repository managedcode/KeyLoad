using Microsoft.CodeAnalysis;

namespace KeyLoad.AnalyzerTests.CodeQuality;

internal sealed class VocabularyPolicyTests
{
    [Test]
    [Arguments("AlternateWord")]
    [Arguments("MovementWord")]
    [Arguments("PriorFailureWord")]
    [Arguments("SubstituteWord")]
    [Arguments("ResourceWord")]
    [Arguments("DataWord")]
    [Arguments("DemonstrationWord")]
    [Arguments("OlderContractWord")]
    public async Task UnapprovedWordsInIdentifiersLiteralsAndCommentsProduceLocatedErrors(string field)
    {
        var word = RuntimePolicyAnalyzerFixture.Word(field);
        foreach (var source in new[]
        {
            $"internal class {word} {{ }}",
            $"internal class Subject {{ const string Value = \"{word}\"; }}",
            $"// {word}\ninternal class Subject {{ }}",
            $"/* {word} */ internal class Subject {{ }}",
            $"/// {word}\ninternal class Subject {{ }}",
            $"/** {word} */ internal class Subject {{ }}",
            $"internal class Subject {{ string Read(int value) => $\"{word}{{value}}\"; }}",
            $"// <auto-generated/>\ninternal class Subject {{ const string Value = \"{word}\"; }}"
        })
        {
            var findings = await RuntimePolicyAnalyzerFixture.AnalyzeAsync(new UnauthorizedImplementationTermAnalyzer(), source);
            await NumericAnalyzerFixture.AssertSingleFindingAsync(findings,
                UnauthorizedImplementationTermAnalyzer.DiagnosticId, DiagnosticSeverity.Error);
            var text = await findings[0].Location.SourceTree!.GetTextAsync();
            await Assert.That(text.ToString(findings[0].Location.SourceSpan))
                .Contains(word);
        }
    }

    [Test]
    public async Task CompoundAndInflectedWordsRetainTheOriginalDiagnosticMeaning()
    {
        var words = new[] { "AlternateWord", "MovementWord", "PriorFailureWord", "SubstituteWord", "ResourceWord", "DataWord", "OlderContractWord" };
        foreach (var field in words)
        {
            var word = RuntimePolicyAnalyzerFixture.Word(field);
            var plural = word.EndsWith("ity", StringComparison.Ordinal) ? word[..^1] + "ies" : word + "s";
            foreach (var text in new[] { plural, "PREFIX" + word.ToUpperInvariant() + "SUFFIX" })
            {
                var source = $"internal class Subject {{ const string Value = \"{text}\"; }}";
                var findings = await RuntimePolicyAnalyzerFixture.AnalyzeAsync(new UnauthorizedImplementationTermAnalyzer(), source);
                await NumericAnalyzerFixture.AssertSingleFindingAsync(findings,
                    UnauthorizedImplementationTermAnalyzer.DiagnosticId, DiagnosticSeverity.Error);
            }
        }
    }

    [Test]
    public async Task ActualFrameworkNamesAndActivationMovementKeepTheirApprovedMeanings()
    {
        var word = RuntimePolicyAnalyzerFixture.Word("MovementWord");
        var source = $$"""
            using System;
            internal class Subject
            {
                const string Description = "Orleans activation {{word}}";
                internal StringComparison Read() => StringComparison.Ordinal;
            }
            """;
        var findings = await RuntimePolicyAnalyzerFixture.AnalyzeAsync(new UnauthorizedImplementationTermAnalyzer(), source);
        await Assert.That(findings).IsEmpty();
    }

    [Test]
    public async Task OrdinaryWordsAndUnrelatedSourceDoNotProduceFindings()
    {
        const string source = "internal class Subject { internal int Read(int value) => value + 1; }";
        var findings = await RuntimePolicyAnalyzerFixture.AnalyzeAsync(new UnauthorizedImplementationTermAnalyzer(), source);
        await Assert.That(findings).IsEmpty();
    }
}
