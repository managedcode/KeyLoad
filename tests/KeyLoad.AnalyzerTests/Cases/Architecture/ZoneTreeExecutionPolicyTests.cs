using Microsoft.CodeAnalysis;

namespace KeyLoad.AnalyzerTests.CodeQuality;

internal sealed class ZoneTreeExecutionPolicyTests
{
    [Test]
    [Arguments("System.Threading.Tasks.Task.Run(() => tree.Count());")]
    [Arguments("System.Threading.Tasks.Task.Factory.StartNew(() => tree.Count());")]
    [Arguments("System.Threading.ThreadPool.QueueUserWorkItem(_ => tree.Count());")]
    [Arguments("System.Threading.ThreadPool.UnsafeQueueUserWorkItem(_ => tree.Count(), null);")]
    [Arguments("System.Threading.Tasks.Task.Run(() => Read(tree));")]
    [Arguments("System.Threading.Tasks.Task.Run(() => new ZoneTree.ZoneTreeFactory<int, int>());")]
    [Arguments("System.Threading.Tasks.Task.Run(() => tree.Maintenance);")]
    public async Task ThreadPoolDispatchCannotHideActualEngineAccess(string statement)
    {
        var source = $$"""
            internal class Subject
            {
                internal void Run(ZoneTree.IZoneTree<int, int> tree) { {{statement}} }
                private static long Read(ZoneTree.IZoneTree<int, int> tree) => tree.Count();
            }
            """;
        var findings = await RuntimePolicyAnalyzerFixture.AnalyzeAsync(new SynchronousZoneTreeAccessAnalyzer(), source);
        await NumericAnalyzerFixture.AssertSingleFindingAsync(findings,
            SynchronousZoneTreeAccessAnalyzer.DiagnosticId, DiagnosticSeverity.Error);
        var text = await findings[0].Location.SourceTree!.GetTextAsync();
        await Assert.That(text.ToString(findings[0].Location.SourceSpan))
            .IsEqualTo(statement.TrimEnd(';'));
    }

    [Test]
    public async Task RealAsynchronousEngineMethodsRemainErrorsInsideGeneratedSources()
    {
        const string source = """
            // <auto-generated/>
            internal class Subject
            {
                internal System.Threading.Tasks.Task Run(ZoneTree.Backup.ILiveBackupRecordWriter writer,
                    ZoneTree.Backup.LiveBackupRecord record, System.Threading.CancellationToken token) => writer.WriteAsync(record, token);
            }
            """;
        var findings = await RuntimePolicyAnalyzerFixture.AnalyzeAsync(new SynchronousZoneTreeAccessAnalyzer(), source);
        await NumericAnalyzerFixture.AssertSingleFindingAsync(findings,
            SynchronousZoneTreeAccessAnalyzer.DiagnosticId, DiagnosticSeverity.Error);
    }

    [Test]
    [Arguments("tree.Count();")]
    [Arguments("System.Threading.Tasks.Task.CompletedTask.GetAwaiter().GetResult();")]
    [Arguments("using var iterator = tree.CreateIterator();")]
    [Arguments("System.Threading.Tasks.Task.Run(() => System.Console.WriteLine(1));")]
    [Arguments("System.Threading.Tasks.Task.Run(() => Read());")]
    [Arguments("System.Threading.Tasks.Task.Run(() => Recurse());")]
    public async Task SynchronousEngineCallsAndActualTransportWorkKeepTheirOwnScheduling(string statement)
    {
        var source = $$"""
            internal class Subject
            {
                internal void Run(ZoneTree.IZoneTree<int, int> tree) { {{statement}} }
                private static void Read() { }
                private static void Recurse() => Recurse();
            }
            """;
        var findings = await RuntimePolicyAnalyzerFixture.AnalyzeAsync(new SynchronousZoneTreeAccessAnalyzer(), source);
        await Assert.That(findings).IsEmpty();
    }
    [Test]
    [Arguments("await using var scope = writer;")]
    [Arguments("await using (writer) { }")]
    [Arguments("await ((System.IAsyncDisposable)writer).DisposeAsync();")]
    public async Task AsynchronousDisposalCannotHideTheEngineBehindAFrameworkInterface(string statement)
    {
        var source = $$"""
            internal class Subject
            {
                internal async System.Threading.Tasks.Task Run(ZoneTree.Backup.ILiveBackupRecordWriter writer)
                {
                    {{statement}}
                }
            }
            """;
        var findings = await RuntimePolicyAnalyzerFixture.AnalyzeAsync(new SynchronousZoneTreeAccessAnalyzer(), source);
        await NumericAnalyzerFixture.AssertSingleFindingAsync(findings,
            SynchronousZoneTreeAccessAnalyzer.DiagnosticId, DiagnosticSeverity.Error);
    }

}
