using Microsoft.CodeAnalysis;

namespace KeyLoad.AnalyzerTests.CodeQuality;

internal sealed class NullReturnTests
{
    [Test]
    [Arguments("string? Read() { return null; }", "null")]
    [Arguments("string? Read() => null;", "null")]
    [Arguments("string Read() => null!;", "null")]
    [Arguments("string? Read() => (string?)null;", "(string?)null")]
    [Arguments("string? Read() => default;", "default")]
    [Arguments("int? Read() => default(int?);", "default(int?)")]
    [Arguments("int? Read() => default;", "default")]
    [Arguments("T? Read<T>() where T : class => default(T);", "default(T)")]
    [Arguments("string? Value => null;", "null")]
    [Arguments("string? Value { get { return null; } }", "null")]
    [Arguments("string? this[int index] => null;", "null")]
    [Arguments("string? Read(bool found) => found ? string.Empty : null;", "null")]
    [Arguments("string? Read(int count) => count switch { 0 => null, _ => string.Empty };", "null")]
    [Arguments("string? Read(string? value) => value ?? null;", "null")]
    [Arguments("string? Read() { const string? value = null; return value; }", "value;")]
    [Arguments("string? Read() { string? Inner() => null; return Inner(); }", "null")]
    [Arguments("System.Func<string?> Read() => () => null;", "null")]
    [Arguments("async System.Threading.Tasks.Task<string?> Read() { await System.Threading.Tasks.Task.Yield(); return null; }", "null")]
    [Arguments("async System.Threading.Tasks.ValueTask<string?> Read() { await System.Threading.Tasks.Task.Yield(); return null; }", "null")]
    public async Task NullOutcomesReportLocatedErrors(string member, string marker)
    {
        var source = "#nullable enable\ninternal class Subject { " + member + " }";
        var findings = await AnalyzerFixture.AnalyzeAsync(new NullReturnAnalyzer(), source);
        await NumericAnalyzerFixture.AssertSingleFindingAsync(findings, NullReturnAnalyzer.DiagnosticId, DiagnosticSeverity.Error);
        var position = source.LastIndexOf(marker, StringComparison.Ordinal);
        await Assert.That(findings[0].Location.SourceSpan.Start).IsEqualTo(position);
        await Assert.That(findings[0].Location.SourceSpan.Length).IsEqualTo(marker.TrimEnd(';').Length);
        await Assert.That(findings[0].GetMessage(System.Globalization.CultureInfo.InvariantCulture))
            .Contains("ManagedCode.Communication.Result");
    }

    [Test]
    [Arguments("// <auto-generated/>\n")]
    [Arguments("")]
    public async Task GeneratedAndOrdinarySourcesHaveTheSameContract(string prefix)
    {
        var source = prefix + "#nullable enable\ninternal class Subject { string? Read() => null; }";
        var findings = await AnalyzerFixture.AnalyzeAsync(new NullReturnAnalyzer(), source, path: AnalyzerFixture.GeneratedPath);
        await NumericAnalyzerFixture.AssertSingleFindingAsync(findings, NullReturnAnalyzer.DiagnosticId, DiagnosticSeverity.Error);
    }

    [Test]
    [Arguments("int Read() => default;")]
    [Arguments("string Read() => string.Empty;")]
    [Arguments("void Read() { return; }")]
    [Arguments("string? Read(string? input) => input;")]
    [Arguments("string Read(string? input) => input ?? string.Empty;")]
    [Arguments("System.Collections.Generic.IEnumerable<string?> Read() { yield return null; }")]
    [Arguments("object? Read() => new object?[] { null };")]
    [Arguments("string Read() => ((string?)null) ?? string.Empty;")]
    public async Task OtherValuesAndPayloadsAreOutsideTheNullReturnRule(string member)
    {
        var source = "#nullable enable\ninternal class Subject { " + member + " }";
        var findings = await AnalyzerFixture.AnalyzeAsync(new NullReturnAnalyzer(), source);
        await Assert.That(findings).IsEmpty();
    }

    [Test]
    public async Task RealCommunicationResultsExpressSuccessAndFailure()
    {
        const string source = """
            using ManagedCode.Communication;
            internal class Subject
            {
                Result<int> Read(bool found) => found ? Result<int>.Succeed(1) : Result<int>.Fail();
                Result Execute() => Result.Succeed();
            }
            """;
        var findings = await RuntimePolicyAnalyzerFixture.AnalyzeAsync(new NullReturnAnalyzer(), source);
        await Assert.That(findings).IsEmpty();
    }
}
