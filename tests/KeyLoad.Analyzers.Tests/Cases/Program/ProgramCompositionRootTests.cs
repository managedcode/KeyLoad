using Microsoft.CodeAnalysis;

namespace KeyLoad.Analyzers.Tests.Features.CodeQuality;

/// <summary>AC-CQ-004: verifies program composition root tests with real compiler fixtures.</summary>
internal sealed class ProgramCompositionRootTests
{
    private const string Id = ProgramCompositionRootAnalyzer.DiagnosticId;
    private const string AggregateSource = """
        using Microsoft.AspNetCore.Builder;
        using Microsoft.Extensions.DependencyInjection;
        internal static class KeyLoadHosting
        {
            internal static IServiceCollection AddKeyLoadServer(this IServiceCollection services)
            {
                services.AddSingleton<System.TimeProvider>(System.TimeProvider.System);
                return services;
            }
            internal static WebApplication UseKeyLoadServer(this WebApplication app)
            {
                app.UseRouting();
                return app;
            }
            internal static WebApplication MapKeyLoadApi(this WebApplication app)
            {
                app.MapGet("/health", () => "ok");
                return app;
            }
        }
        """;

    /// <summary>Verifies aggregate composition is allowed.</summary>
    [Test]
    public async Task AggregateCompositionIsAllowedAsync()
    {
        const string source = """
            using Microsoft.AspNetCore.Builder;
            var builder = WebApplication.CreateBuilder();
            builder.Services.AddKeyLoadServer();
            var app = builder.Build();
            app.UseKeyLoadServer();
            app.MapKeyLoadApi();
            app.Run();
            public partial class Program;
            """;
        var findings = await AnalyzerFixture.AnalyzeAsync(new ProgramCompositionRootAnalyzer(),
            source, AnalyzerFixture.ServerAssembly, AnalyzerFixture.ProgramPath, executable: true,
            additionalSource: AggregateSource);
        await Assert.That(findings).IsEmpty();
    }

    /// <summary>Verifies visible concrete registration is allowed.</summary>
    [Test]
    public async Task ConcreteRegistrationIsAllowedAsync()
    {
        const string source = """
            using Microsoft.AspNetCore.Builder;
            using Microsoft.Extensions.DependencyInjection;
            var builder = WebApplication.CreateBuilder();
            builder.Services.AddSingleton<System.TimeProvider>(System.TimeProvider.System);
            """;
        var findings = await AnalyzerFixture.AnalyzeAsync(new ProgramCompositionRootAnalyzer(),
            source, AnalyzerFixture.ServerAssembly, AnalyzerFixture.ProgramPath, executable: true,
            additionalSource: AggregateSource);
        await Assert.That(findings).IsEmpty();
    }

    /// <summary>Verifies visible local lifecycle helpers are allowed.</summary>
    [Test]
    public async Task HelperDeclarationIsAllowedAsync()
    {
        const string source = """
            using Microsoft.AspNetCore.Builder;
            var builder = WebApplication.CreateBuilder();
            static void ConfigureServices() => System.Console.WriteLine("configured");
            """;
        var findings = await AnalyzerFixture.AnalyzeAsync(new ProgramCompositionRootAnalyzer(),
            source, AnalyzerFixture.ServerAssembly, AnalyzerFixture.ProgramPath, executable: true,
            additionalSource: AggregateSource);
        await Assert.That(findings).IsEmpty();
    }

    /// <summary>Verifies non program file is ignored.</summary>
    [Test]
    public async Task NonProgramFileIsIgnoredAsync()
    {
        const string source = """
            Application.Run(args);
            internal static class Application { internal static void Run(string[] args) { } }
            """;
        var findings = await AnalyzerFixture.AnalyzeAsync(new ProgramCompositionRootAnalyzer(),
            source, AnalyzerFixture.ServerAssembly, AnalyzerFixture.ServerHostingPath, executable: true,
            additionalSource: AggregateSource);
        await Assert.That(findings).IsEmpty();
    }

    /// <summary>Verifies generated program is ignored.</summary>
    [Test]
    public async Task GeneratedProgramIsIgnoredAsync()
    {
        const string source = """
            // <auto-generated/>
            Application.Run(args);
            internal static class Application { internal static void Run(string[] args) { } }
            """;
        var findings = await AnalyzerFixture.AnalyzeAsync(new ProgramCompositionRootAnalyzer(),
            source, AnalyzerFixture.ServerAssembly, AnalyzerFixture.ProgramPath, executable: true,
            additionalSource: AggregateSource);
        await Assert.That(findings).IsEmpty();
    }

    /// <summary>Rejects forwarding-only synchronous, asynchronous and exit-code entry points.</summary>
    [Test]
    [Arguments("Application.Run(args);", "internal static void Run(string[] args) { }")]
    [Arguments("await Application.RunAsync(args);", "internal static System.Threading.Tasks.Task RunAsync(string[] args) => System.Threading.Tasks.Task.CompletedTask;")]
    [Arguments("await Application.RunAsync(args).ConfigureAwait(false);", "internal static System.Threading.Tasks.Task RunAsync(string[] args) => System.Threading.Tasks.Task.CompletedTask;")]
    [Arguments("return await Application.RunAsync(args);", "internal static System.Threading.Tasks.Task<int> RunAsync(string[] args) => System.Threading.Tasks.Task.FromResult(0);")]
    [Arguments("return Application.Run(args);", "internal static int Run(string[] args) => 0;")]
    public async Task ForwardingOnlyEntryReportsLocatedErrorAsync(string entry, string method)
    {
        var source = entry + "\ninternal static class Application { " + method + " }";
        var findings = await AnalyzerFixture.AnalyzeAsync(new ProgramCompositionRootAnalyzer(),
            source, AnalyzerFixture.ServerAssembly, AnalyzerFixture.ProgramPath, executable: true);
        await AnalyzerFixture.AssertFindingAsync(findings, Id, DiagnosticSeverity.Error,
            source, entry, AnalyzerFixture.ProgramPath);
    }

    [Test]
    [Arguments("if (args.Length > 0) System.Console.WriteLine(args[0]);")]
    [Arguments("System.Console.WriteLine(args.Length);")]
    [Arguments("System.Console.ReadLine();")]
    [Arguments("return 0;")]
    public async Task DirectStatementsAndNonLifecycleCallsKeepVisibleComposition(string source)
    {
        var findings = await AnalyzerFixture.AnalyzeAsync(new ProgramCompositionRootAnalyzer(), source,
            AnalyzerFixture.ServerAssembly, AnalyzerFixture.ProgramPath, executable: true);
        await Assert.That(findings).IsEmpty();
    }

}
