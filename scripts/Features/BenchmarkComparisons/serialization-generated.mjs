import { lstat, readdir } from 'node:fs/promises';
import { join } from 'node:path';
import { EXECUTION, runtimeRequire } from './serialization-contract.mjs';
import { copyOriginal, walkFiles } from './serialization-files.mjs';

export async function generatedDirectories() {
  const entries = await readdir(EXECUTION.bin, { withFileTypes: true });
  const directories = [];
  for (const entry of entries.filter(value => value.isDirectory())) {
    const root = join(EXECUTION.bin, entry.name);
    try {
      const info = await lstat(join(root, 'BenchmarkDotNet.Autogenerated.csproj'));
      runtimeRequire(info.isFile() && !info.isSymbolicLink(), 'generated.project');
      directories.push(entry.name);
    } catch (error) {
      if (error.code !== 'ENOENT') throw error;
    }
  }
  return directories.sort();
}

function retainedFile(path, directory) {
  return path.endsWith('.notcs') || path.endsWith('.sh') || path.endsWith('.log')
    || path.endsWith('BenchmarkDotNet.Autogenerated.csproj') || path.endsWith('project.assets.json')
    || path.endsWith('.deps.json') || path.endsWith('.runtimeconfig.json')
    || ['KeyLoad.BenchmarkScenarios.dll', 'KeyLoad.Abstractions.dll', 'Orleans.Serialization.dll',
      'BenchmarkDotNet.dll', `${directory}.dll`].includes(path.split('/').at(-1));
}

export async function captureGenerated(directory, previous) {
  // BDN reuses deterministic assembly/job partition names. A preceding generated-Dry
  // process can have created the same directory, which the measured build overwrites.
  const children = (await generatedDirectories()).filter(name =>
    name.includes(`-${EXECUTION.jobId}-`) || !previous.includes(name));
  runtimeRequire(children.length > 0 && children.length <= 12, 'generated.children');
  const copied = [];
  for (const child of children) {
    const root = join(EXECUTION.bin, child);
    const files = (await walkFiles(root)).filter(path => retainedFile(path, child));
    runtimeRequire(files.some(path => path.endsWith('.notcs'))
      && files.includes('BenchmarkDotNet.Autogenerated.csproj')
      && files.some(path => path.endsWith(`/${child}.dll`)), 'generated.actualChild');
    for (const file of files) {
      const destination = `generated/${child}/${file}`;
      await copyOriginal(join(root, file), join(directory, destination));
      copied.push(destination);
    }
  }
  return copied.sort();
}
